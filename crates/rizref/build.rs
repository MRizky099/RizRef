//! Embeds the application icon and version information into `rizref.exe`.
//!
//! Windows reads an exe's icon (Explorer, the taskbar, the `.rizref` file
//! icon via `DefaultIcon = "rizref.exe",1`) and its *Details* tab from
//! compiled resources. The usual route is `rc.exe` or `windres`, a C toolchain
//! component; this script writes the compiled `.res` itself — it is a simple,
//! documented binary format — and hands it to the MSVC linker, which accepts
//! `.res` inputs directly. Pure Rust, no tool on `PATH`, no dependency.
//!
//! Resources (`resources.rs`): two `RT_GROUP_ICON`s — id 1 from
//! `assets/rizref.ico`, the application (icon index 0), and id 2 from
//! `assets/rizref_document.ico`, the `.rizref` file icon (index 1, which
//! `rizref register` names in `DefaultIcon`) — their `RT_ICON` images, and
//! `RT_VERSION` from the package version. Only MSVC targets get them; other
//! toolchains build without.

use std::path::{Path, PathBuf};

mod resources;

fn main() {
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets it"));
    let icons = [
        manifest.join("assets").join("rizref.ico"),
        manifest.join("assets").join("rizref_document.ico"),
    ];
    for icon in &icons {
        println!("cargo:rerun-if-changed={}", icon.display());
    }
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=resources.rs");

    let target = std::env::var("TARGET").unwrap_or_default();
    if !target.ends_with("windows-msvc") {
        return;
    }
    // The icons are generated by `cargo run -p rizref --example make_icon`,
    // which itself needs this crate to build: without them, embed the
    // version information only.
    let icos: Vec<Vec<u8>> = icons
        .iter()
        .map(|icon| {
            std::fs::read(icon).unwrap_or_else(|_| {
                println!(
                    "cargo:warning=no {} yet; building without it",
                    icon.display()
                );
                Vec::new()
            })
        })
        .collect();
    let version = std::env::var("CARGO_PKG_VERSION").expect("cargo sets it");
    let slices: Vec<&[u8]> = icos.iter().map(Vec::as_slice).collect();
    let res = resources::build_res(&slices, &version);
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets it")).join("rizref.res");
    std::fs::write(&out, res).expect("write the resource file");
    link(&out);
}

fn link(res: &Path) {
    // `-bins` keeps the resources out of test and example executables.
    println!("cargo:rustc-link-arg-bins={}", res.display());
}
